def test_python_modules_vendoring_structure():
    """
    Verify that if python_modules is present (generated by pywrangler sync),
    it contains the required packages for Cloudflare Workers Pyodide runtime.
    """
    python_modules_dir = Path("python_modules")
    if python_modules_dir.exists():
        assert (python_modules_dir / "fastapi").is_dir()
        assert (python_modules_dir / "pydantic").is_dir()
        assert (python_modules_dir / "workers").is_dir()
        assert (python_modules_dir / "tzdata").is_dir()
